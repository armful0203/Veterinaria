-- Usa comandos de psql (\gexec y \connect); no ejecutar completo en Query Tool.
-- No borra registros. En una base existente inserta los ejemplos solo si la tabla esta vacia.
-- El usuario y la clave coinciden con application.properties del proyecto de practica.
SELECT 'CREATE ROLE kevin LOGIN PASSWORD ''123'''
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'kevin')\gexec
SELECT 'CREATE DATABASE veterinaria OWNER kevin'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'veterinaria')\gexec
\connect veterinaria
GRANT CONNECT ON DATABASE veterinaria TO kevin;
GRANT USAGE, CREATE ON SCHEMA public TO kevin;
SET ROLE kevin;

CREATE TABLE IF NOT EXISTS mascota (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255), edad integer NOT NULL, especie varchar(255), dueno varchar(255)
);
CREATE TABLE IF NOT EXISTS medicamento (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255), precio double precision NOT NULL, stock integer NOT NULL,
    requiere_receta boolean NOT NULL
);
CREATE TABLE IF NOT EXISTS veterinario (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255), especialidad varchar(255), anios_experiencia integer NOT NULL,
    disponible boolean NOT NULL
);

